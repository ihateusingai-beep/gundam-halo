#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    // Load animation frames at startup so the tray is animated as soon as
    // it appears. If loading fails, we fall back to the default window icon
    // and the tray stays static.
    let anim_frames = load_animation_frames().ok();

    tauri::Builder::default()
        .plugin(tauri_plugin_shell::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_global_shortcut::Builder::new().build())
        .plugin(tauri_plugin_autostart::init(
            tauri_plugin_autostart::MacosLauncher::LaunchAgent,
            Some(vec!["--minimized"]),
        ))
        .setup(move |app| {
            // ---- Tray menu ----
            // Order: Show → Hide → ─── → New Chat → Settings → ─── → Quit
            let show = MenuItem::with_id(app, "show", "Open Dashboard", true, None::<&str>)?;
            let hide = MenuItem::with_id(app, "hide", "Hide to Tray", true, None::<&str>)?;
            let sep1 = PredefinedMenuItem::separator(app)?;
            let new_chat =
                MenuItem::with_id(app, "new-chat", "New Chat", true, Some("CmdOrCtrl+N"))?;
            let settings =
                MenuItem::with_id(app, "settings", "Settings…", true, Some("CmdOrCtrl+,"))?;
            let sep2 = PredefinedMenuItem::separator(app)?;
            let quit =
                MenuItem::with_id(app, "quit", "Quit Gundam Halo", true, Some("CmdOrCtrl+Q"))?;

            let menu = Menu::with_items(
                app,
                &[&show, &hide, &sep1, &new_chat, &settings, &sep2, &quit],
            )?;

            // ---- Tray icon ----
            // Pick the first animation frame as the *initial* icon (so the
            // tray appears correctly before the animation thread kicks in).
            // The thread will overwrite it ~67 ms later.
            let initial_icon = match &anim_frames {
                Some(frames) if !frames.is_empty() => frames[0].clone(),
                _ => app
                    .default_window_icon()
                    .ok_or("no default window icon and no animation frames")?
                    .to_owned(),
            };

            let _tray = TrayIconBuilder::with_id("main-tray")
                .tooltip("Gundam Halo — personal AI agent")
                .icon(initial_icon)
                .menu(&menu)
                .show_menu_on_left_click(false)
                .on_menu_event(|app, event| match event.id.as_ref() {
                    "quit" => {
                        app.exit(0);
                    }
                    "show" => show_main_window(app),
                    "hide" => hide_main_window(app),
                    "new-chat" => {
                        show_main_window(app);
                        let _ = app.emit("halo://new-chat", ());
                    }
                    "settings" => {
                        show_main_window(app);
                        let _ = app.emit("halo://open-settings", ());
                    }
                    _ => {}
                })
                .on_tray_icon_event(|tray, event| {
                    if let TrayIconEvent::Click {
                        button: MouseButton::Left,
                        button_state: MouseButtonState::Up,
                        ..
                    } = event
                    {
                        toggle_main_window(tray.app_handle());
                    }
                })
                .build(app)?;

            // ---- Animation thread ----
            if let Some(frames) = anim_frames.clone() {
                let stop_flag = spawn_animation_thread(app.handle().clone(), frames);
                // Stash the stop flag on the app state so we could signal it
                // from elsewhere in the future (e.g. "pause animation when
                // battery < 20%"). For now the thread runs until process exit.
                app.manage(AnimationStop(stop_flag));
            }

            // If launched with --minimized (e.g. autostart on login), keep
            // the window hidden so the agent lives in the tray.
            if launched_minimized() {
                hide_main_window(&app.handle());
            }

            Ok(())
        })
        // macOS: clicking the dock icon while the window is hidden should
        // bring it back, not just show an empty placeholder.
        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                // Closing the window hides it to the tray instead of quitting.
                // Quit explicitly via the tray menu.
                let _ = window.hide();
                api.prevent_close();
            }
        })
        .invoke_handler(tauri::generate_handler![
            focus_main_window,
            hide_main_window_cmd,
            new_chat,
            open_settings,
            set_animation_speed,
            get_animation_speed,
            restart_backend
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

/// Wrapper so we can store the animation thread's stop flag in Tauri's
/// state container. Currently unused at runtime but reserved for future
/// hooks (battery saver, focus-state pause, etc.).
#[allow(dead_code)]
struct AnimationStop(Arc<AtomicBool>);

