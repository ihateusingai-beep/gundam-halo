"""SQLite index for sessions, messages, and threads.

Layered on top of the file-based persistence in
``app.projects.persistence``. The JSON files remain the source of
truth; this SQLite DB is a *queryable index* — fast lookups, filters,
counts, joins. It can always be regenerated by walking the JSON
files (see ``app.memory.lifecycle.rebuild_index``).

Threading
---------
This module opens **one** SQLite connection per ``SqliteIndex``
instance. We do *not* use a connection pool — the WAL mode
(``PRAGMA journal_mode=WAL``) plus ``check_same_thread=False``
makes the same connection safe to use from multiple threads in
our usage pattern (short-lived transactions, no long-held cursors).

If you need to share the index across many concurrent writers,
open one connection per thread via ``SqliteIndex.for_thread()``.

Schema
------
See ``M12 ticket`` for the full DDL. Schema version is
``SCHEMA_VERSION``; if the on-disk version is older we run a
rebuild.
"""
from __future__ import annotations

import json
import logging
import sqlite3
import threading
import time
from collections.abc import Iterator, Sequence
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Schema
# ---------------------------------------------------------------------------

SCHEMA_VERSION = 1

# Order matters: foreign keys depend on the parent table existing.
SCHEMA_DDL: tuple[str, ...] = (
    """
    CREATE TABLE IF NOT EXISTS schema_meta (
        key   TEXT PRIMARY KEY,
        value TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS sessions (
        session_id    TEXT PRIMARY KEY,
        project_name  TEXT NOT NULL,
        agent_type    TEXT NOT NULL,
        channel       TEXT,
        created_at    REAL NOT NULL,
        updated_at    REAL NOT NULL,
        message_count INTEGER NOT NULL DEFAULT 0
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_sessions_project ON sessions(project_name)",
    "CREATE INDEX IF NOT EXISTS idx_sessions_updated ON sessions(updated_at DESC)",
    """
    CREATE TABLE IF NOT EXISTS messages (
        message_id    INTEGER PRIMARY KEY AUTOINCREMENT,
        session_id    TEXT NOT NULL REFERENCES sessions(session_id) ON DELETE CASCADE,
        seq           INTEGER NOT NULL,
        role          TEXT NOT NULL,
        content       TEXT NOT NULL,
        tool_calls    TEXT,
        tool_call_id  TEXT,
        name          TEXT,
        created_at    REAL NOT NULL,
        UNIQUE (session_id, seq)
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_messages_session ON messages(session_id, seq)",
    "CREATE INDEX IF NOT EXISTS idx_messages_role ON messages(role)",
    """
    CREATE TABLE IF NOT EXISTS threads (
        thread_id     TEXT PRIMARY KEY,
        name          TEXT NOT NULL,
        project_name  TEXT,
        created_at    REAL NOT NULL,
        updated_at    REAL NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS session_thread (
        session_id  TEXT NOT NULL REFERENCES sessions(session_id) ON DELETE CASCADE,
        thread_id   TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
        PRIMARY KEY (session_id, thread_id)
    )
    """,
)


