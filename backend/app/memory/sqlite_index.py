@dataclass(slots=True, frozen=True)
class SessionRow:
    session_id: str
    project_name: str
    agent_type: str
    channel: str | None
    created_at: float
    updated_at: float
    message_count: int

    def to_dict(self) -> dict[str, Any]:
        return {
            "session_id": self.session_id,
            "project_name": self.project_name,
            "agent_type": self.agent_type,
            "channel": self.channel,
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "message_count": self.message_count,
        }


@dataclass(slots=True, frozen=True)
class MessageRow:
    message_id: int
    session_id: str
    seq: int
    role: str
    content: str
    tool_calls: str | None  # JSON string
    tool_call_id: str | None
    name: str | None
    created_at: float

    def snippet(self, limit: int = 240) -> str:
        """Truncate content for previews (respects UTF-8 boundaries)."""
        if len(self.content) <= limit:
            return self.content
        # Cut on a character boundary
        return self.content[:limit].rsplit(" ", 1)[0] + "..."

    def to_dict(self) -> dict[str, Any]:
        return {
            "message_id": self.message_id,
            "session_id": self.session_id,
            "seq": self.seq,
            "role": self.role,
            "content": self.content,
            "tool_calls": json.loads(self.tool_calls) if self.tool_calls else None,
            "tool_call_id": self.tool_call_id,
            "name": self.name,
            "created_at": self.created_at,
        }


# ---------------------------------------------------------------------------
# Helpers
